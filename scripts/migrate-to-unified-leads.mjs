/**
 * scripts/migrate-to-unified-leads.mjs
 *
 * One-time migration: pull every lead source into homeowner_requests so the
 * /admin lead inbox + /dialer queue can read from a single table.
 *
 * Reads data/vault_listings.ndjson, generates a SQL file with INSERT ON
 * CONFLICT DO UPDATE statements, writes it to /tmp/. The script then
 * prints the supabase CLI command to run it (since we use the CLI for
 * Supabase access — Patrick's .env.local key was malformed).
 *
 * Idempotent: upserts on pipeline_lead_key.
 *
 * Run:
 *   node scripts/migrate-to-unified-leads.mjs
 */

import fs from "node:fs"
import path from "node:path"
import { execSync } from "node:child_process"

const NDJSON_PATH = path.join(process.cwd(), "data", "vault_listings.ndjson")
const OUT_SQL = path.join(process.cwd(), "scripts", "supabase", "_unified_leads_migration.sql")

function escSql(value) {
  if (value === null || value === undefined) return "NULL"
  if (typeof value === "number") return String(value)
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE"
  // Postgres string escape — single quotes doubled, NULL bytes stripped
  const s = String(value).replace(/\u0000/g, "").replace(/'/g, "''")
  return `'${s}'`
}

function toIsoDate(raw) {
  if (!raw) return null
  const s = String(raw).trim()
  if (!s) return null
  if (s.includes("T")) return s.split("T", 1)[0]
  return s.slice(0, 10)
}
function toInt(raw) {
  if (raw === null || raw === undefined || raw === "") return null
  const n = Number(raw)
  return Number.isFinite(n) ? Math.round(n) : null
}
function toFloat(raw) {
  if (raw === null || raw === undefined || raw === "") return null
  const n = Number(raw)
  return Number.isFinite(n) ? n : null
}
function nonEmpty(raw) {
  if (raw === null || raw === undefined) return null
  const s = String(raw).trim()
  return s ? s : null
}

function readVaultNdjson() {
  if (!fs.existsSync(NDJSON_PATH)) {
    console.error(`vault_listings.ndjson not found at ${NDJSON_PATH}`)
    process.exit(2)
  }
  const lines = fs
    .readFileSync(NDJSON_PATH, "utf8")
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
  return lines.flatMap((line) => {
    try { return [JSON.parse(line)] } catch { return [] }
  })
}

function vaultToFields(v) {
  const distressType = (() => {
    const dt = String(v.distressType || "").toLowerCase()
    if (dt.includes("trustee") || dt.includes("foreclosure")) return "TRUSTEE_NOTICE"
    if (dt.includes("lis") && dt.includes("pendens")) return "LIS_PENDENS"
    if (dt.includes("nod")) return "NOD"
    if (dt.includes("preforeclosure") || dt.includes("pre-foreclosure")) return "PREFORECLOSURE"
    if (dt.includes("tax")) return "TAX_LIEN"
    if (dt.includes("probate")) return "PROBATE"
    if (dt.includes("fsbo")) return "FSBO"
    return v.distressType ? String(v.distressType).toUpperCase().slice(0, 60) : null
  })()

  return {
    source: "bot",
    pipeline_lead_key: nonEmpty(v.slug),
    full_name: nonEmpty(v.ownerName),
    owner_name_records: nonEmpty(v.ownerName),
    phone: nonEmpty(v.ownerPhonePrimary),
    property_address: nonEmpty(v.address) || nonEmpty(v.title) || "",
    county: nonEmpty(v.county),
    trustee_sale_date: toIsoDate(v.currentSaleDate),
    mortgage_balance: toInt(v.mortgageAmount),
    distress_type: distressType,
    beds: toInt(v.beds),
    baths: toFloat(v.baths),
    sqft: toInt(v.buildingAreaSqft),
    year_built: toInt(v.yearBuilt),
    last_sale_date: toIsoDate(v.lastSaleDate),
    pipeline_score: toInt(v.falcoScore),
  }
}

function buildUpsertSql(fields) {
  const cols = Object.keys(fields)
  const vals = cols.map((c) => escSql(fields[c]))
  const updateAssignments = cols
    .filter((c) => c !== "pipeline_lead_key" && c !== "source")
    .map((c) => `${c} = excluded.${c}`)
    .join(",\n        ")
  // pipeline_lead_key has a partial unique index (WHERE pipeline_lead_key
  // IS NOT NULL) — Postgres requires the same predicate on ON CONFLICT
  // to target a partial index.
  return `insert into public.homeowner_requests (${cols.join(", ")}) values (${vals.join(", ")})
  on conflict (pipeline_lead_key) where pipeline_lead_key is not null do update set
        ${updateAssignments};`
}

function main() {
  console.log("[migrate] reading vault_listings.ndjson…")
  const vault = readVaultNdjson()
  console.log(`[migrate] ${vault.length} entries to migrate`)

  if (vault.length === 0) {
    console.log("[migrate] nothing to migrate")
    return
  }

  const stmts = []
  stmts.push("-- Auto-generated by scripts/migrate-to-unified-leads.mjs")
  stmts.push("-- One-time migration: vault NDJSON → homeowner_requests")
  stmts.push("-- Idempotent (upserts on pipeline_lead_key)")
  stmts.push("")
  for (const v of vault) {
    const fields = vaultToFields(v)
    if (!fields.pipeline_lead_key || !fields.property_address) {
      console.warn(`[migrate] skipping entry — missing slug or address`)
      continue
    }
    stmts.push(buildUpsertSql(fields))
    stmts.push("")
  }

  fs.mkdirSync(path.dirname(OUT_SQL), { recursive: true })
  fs.writeFileSync(OUT_SQL, stmts.join("\n"))
  console.log(`[migrate] wrote ${stmts.length} SQL statements → ${OUT_SQL}`)

  console.log("[migrate] executing via supabase CLI…")
  try {
    const result = execSync(`supabase db query --linked --file "${OUT_SQL}"`, {
      cwd: process.cwd(),
      encoding: "utf8",
      stdio: ["inherit", "pipe", "pipe"],
    })
    console.log(result.trim().slice(-300))
    console.log("[migrate] done.")
  } catch (e) {
    console.error("[migrate] supabase CLI execution failed:")
    console.error(e.stderr || e.message)
    console.error(`SQL file is at ${OUT_SQL} — you can re-run manually.`)
    process.exit(1)
  }
}

main()
