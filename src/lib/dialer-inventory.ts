/**
 * Sales motion buckets — which conversation fits this lead.
 * Generated by classifyPitchBucket() from distress_type + equity ratio
 * + owner type. Drives the lead-detail "Pitch" panel and per-bucket
 * math/outreach templates.
 *
 *  EQUITY_PROTECT     PRE_FC + ≥20% equity. Math sheet first (gold path).
 *  LLC_INVESTOR       Owner is LLC/Inc/Corp. Investor-to-investor terms.
 *  CODE_VIOLATION     Metro Codes / Hamilton / Memphis violations.
 *  LOW_EQUITY_FC      PRE_FC but <20% equity. Stop-the-sale + relocation.
 *  PROBATE            Estate property, talking to executor.
 *  FSBO               Owner already trying to sell. Auction-vs-MLS pitch.
 *  BANKRUPTCY         Chapter 7/13. Trustee + attorney involved.
 *  UNDERWATER         Mortgage > AVM. Short-sale / DIL / cash-for-keys.
 *  UNCLASSIFIED       Lead missing distress signal or owner data.
 */
export type PitchBucket =
  | "EQUITY_PROTECT"
  | "LLC_INVESTOR"
  | "CODE_VIOLATION"
  | "LOW_EQUITY_FC"
  | "PROBATE"
  | "FSBO"
  | "BANKRUPTCY"
  | "UNDERWATER"
  | "UNCLASSIFIED"

const LLC_MARKERS = [
  " LLC", " L.L.C", " INC", " CORP", " COMPANY", " CO.",
  " TRUST", " LP ", " LP,", " L.P.", " LLP",
  " HOLDINGS", " PROPERTIES", " PARTNERS", " GROUP",
  " ENTERPRISES", " MANAGEMENT",
] as const

function looksLikeEntity(name: string | null | undefined): boolean {
  if (!name) return false
  const padded = " " + name.toUpperCase() + " "
  return LLC_MARKERS.some((m) => padded.includes(m))
}

export function classifyPitchBucket(args: {
  distressType: string | null | undefined
  ownerName: string | null | undefined
  propertyValue: number | null | undefined
  mortgageBalance: number | null | undefined
}): PitchBucket {
  const dt = (args.distressType || "").toUpperCase()
  const owner = args.ownerName || ""
  const pv = args.propertyValue || 0
  const mb = args.mortgageBalance || 0
  const equityRatio = pv > 0 && mb > 0 ? (pv - mb) / pv : null

  // LLC/entity wins regardless of distress — different motion entirely
  if (looksLikeEntity(owner)) return "LLC_INVESTOR"

  // Underwater wins next — math sheet would deflate the call
  if (equityRatio !== null && equityRatio < 0) return "UNDERWATER"

  // Distress-type-driven branches
  if (dt === "PROBATE") return "PROBATE"
  if (dt === "CODE_VIOLATION") return "CODE_VIOLATION"
  if (dt === "TAX_LIEN") return "CODE_VIOLATION"  // similar liability-transfer pitch
  if (dt === "BANKRUPTCY") return "BANKRUPTCY"
  if (dt === "FSBO") return "FSBO"

  // Foreclosure family — split by equity
  if (
    dt === "PRE_FORECLOSURE" ||
    dt === "TRUSTEE_NOTICE" ||
    dt === "FORECLOSURE" ||
    dt === "LIS_PENDENS"
  ) {
    if (equityRatio !== null && equityRatio >= 0.2) return "EQUITY_PROTECT"
    if (equityRatio !== null && equityRatio < 0.2) return "LOW_EQUITY_FC"
    // No equity data — default to EQUITY_PROTECT, rep can downgrade if needed
    return "EQUITY_PROTECT"
  }

  return "UNCLASSIFIED"
}

export type DialerInventorySnapshot = {
  generatedAt: string
  leads: DialerInventoryLead[]
}

/** Raw snapshot loader — reads the JSON blob in partner_access_requests.
 *  Used as a structural-data backup. Phone/email/AVM in the snapshot may
 *  be stale; loadDialerInventory() merges fresh data from homeowner_requests
 *  on top before returning. */
async function loadRawSnapshot(): Promise<DialerInventorySnapshot | null> {
  if (!supabaseAdmin) return null

  const { data, error } = await supabaseAdmin
    .from("partner_access_requests")
    .select("notes, created_at")
    .eq("company", SYSTEM_STATE_COMPANY)
    .eq("status", "state_snapshot")
    .eq("email", INVENTORY_EMAIL)
    .order("created_at", { ascending: false })
    .limit(1)
    .maybeSingle()

  if (error) {
    if (error.code !== "PGRST116") {
      console.error("loadRawSnapshot error:", error.message)
    }
    return null
  }
  if (!data?.notes) return null

  try {
    const envelope = JSON.parse(data.notes as string)
    const payload = envelope?.payload
    if (!payload || !Array.isArray(payload.leads)) return null
    return {
      generatedAt: String(envelope.updatedAt ?? payload.generatedAt ?? ""),
      leads: payload.leads as DialerInventoryLead[],
    }
  } catch (err) {
    console.error("loadRawSnapshot parse error:", err)
    return null
  }
}

